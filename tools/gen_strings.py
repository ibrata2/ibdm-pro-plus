# Builds src/IbdmPro.Core/Strings.cs (Arabic → English) from tools/strings-keys.json + tools/strings-en.txt.
# Keys are the C# source text of each Arabic string, so escapes like \n match exactly.
import json, sys
root = sys.argv[1]
keys = json.load(open(f'{root}/tools/strings-keys.json', encoding='utf-8'))
en = open(f'{root}/tools/strings-en.txt', encoding='utf-8').read().split('\n')
if en[-1] == '': en = en[:-1]
assert len(keys) == len(en), (len(keys), len(en))
extra = {  # names of the built-in file types (they stay Arabic in the settings file)
    'فيديو': 'Video', 'صوتيات': 'Audio', 'مضغوطات': 'Compressed', 'برامج': 'Programs', 'مستندات': 'Documents',
    'صور': 'Images', 'تورنت': 'Torrent', 'أخرى': 'Other',
}
pairs = dict(zip(keys, en))
for k, v in extra.items(): pairs.setdefault(k, v)
q = lambda s: '"' + s.replace('"', '\\"') + '"'
lines = [f'        [{ "" }"{k}"] = {q(v)},' if False else f'        [{q(k) if chr(92) not in k else chr(34) + k + chr(34)}] = {q(v)},' for k, v in pairs.items()]
out = '''// Generated by tools/gen_strings.py — edit tools/strings-en.txt, not this file.
namespace IbdmPro.Core;

public static partial class L
{
    private static readonly Dictionary<string, string> English = new()
    {
''' + '\n'.join(lines) + '''
    };
}
'''
open(f'{root}/src/IbdmPro.Core/Strings.cs', 'w', encoding='utf-8').write(out)
print(len(pairs), 'strings')
